CREATE TABLE `leads` (
	`id` text PRIMARY KEY NOT NULL,
	`name` text NOT NULL,
	`salary` text NOT NULL,
	`occupation` text NOT NULL,
	`property_type` text NOT NULL,
	`budget` text NOT NULL,
	`phone` text NOT NULL,
	`whatsapp` integer NOT NULL,
	`language` text NOT NULL,
	`created_at` text NOT NULL
);
